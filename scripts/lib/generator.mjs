function p2Body(intent) {
  return `# ${title(intent.name)}\n\n## why: purpose\n\n${intent.problem.trim()}\n\n## stage: operate\n\nJudgment: authoring.readiness is one of ready, needs-design, or complete. Confirm that the user-specific contract has replaced the generic authoring scaffold before treating the skill as behavior-complete.\n\nWhy: Structural validity alone cannot prove that the user's intended behavior was preserved.\n`;
}

function p2Scenarios() {
  return [
    { id: "ready", s: {}, decided: { "authoring.readiness": "ready" }, expect: { stage: "operate", status: "DONE", effects: ["REPORT", "DONE"] }, cover: ["stage:operate", "branch:operate/ready"] },
    { id: "needs-design", s: {}, decided: { "authoring.readiness": "needs-design" }, expect: { stage: "operate", status: "BLOCK" }, cover: ["branch:operate/needs-design"] },
    { id: "complete", s: {}, decided: { "authoring.readiness": "complete" }, expect: { stage: null, status: "DONE" }, cover: [] }
  ];
}

function lintMutationCases() {
  const operations = [
    "extra-export", "ambient-authority", "observation-source", "invalid-domain", "reads-mismatch", "table-default",
    "stage-contract", "body-section", "body-duplicate-procedure", "stage-signature", "artifact-readers", "template-placeholder",
    "role-state-effect", "language-parity", "fixture-coverage", "format-domain", "deferred-shape", "mutation-manifest", "unsafe-bypass"
  ];
  return [
    ...operations.map((operation, index) => ({ id: `negative-L${index}`, expected_code: `L${index}`, mutation: { operation } })),
    { id: "negative-L15-format-golden", expected_code: "L15", mutation: { operation: "format-golden" } }
  ];
}

function workflowLines(intent) {
  const lines = [];
  for (const item of intent.use_cases ?? []) lines.push(`- Handle: ${item}`);
  for (const item of intent.completion_evidence ?? []) lines.push(`- Verify completion with: ${item}`);
  return lines.length > 0 ? lines : ["- Interpret the request against the recorded problem and produce the declared output."];
}

function renderIntentSections(intent) {
  return INTENT_ARRAYS.map((field) => `## ${title(field.replaceAll("_", "-"))}\n\n${bullets(intent[field])}`).join("\n\n");
}

function bullets(items = []) { return items.length > 0 ? items.map((item) => `- ${item}`).join("\n") : "- none"; }
function shortDescription(text) { return String(text).replace(/\s+/g, " ").trim().slice(0, 80); }
function title(name) { return String(name).split("-").map((part) => part ? part[0].toUpperCase() + part.slice(1) : part).join(" "); }

export { AUTHORING_ROOT };
